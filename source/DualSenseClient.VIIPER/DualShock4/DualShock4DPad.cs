namespace DualSenseClient.VIIPER.DualShock4;

/// <summary>
/// DualShock 4 D-pad hat switch values.
/// </summary>
public enum DualShock4DPad : byte
{
    Up = 0x00,
    UpRight = 0x01,
    Right = 0x02,
    DownRight = 0x03,
    Down = 0x04,
    DownLeft = 0x05,
    Left = 0x06,
    UpLeft = 0x07,
    Neutral = 0x08
}